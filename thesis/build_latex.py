def make_references_tex(md: str) -> str:
    """Bibliography from 07_references.md. We do NOT use bibtex — we just emit
    a 'Bibliography' chapter with numbered entries (in citation order)."""
    body = md_to_latex(md)
    # Replace the auto-generated \chapter{Bibliography} (Pandoc gives it) with
    # \chapter* so it doesn't count in the chapter numbering; still ToC-listed.
    body = re.sub(r"\\chapter\{Bibliography\}\\label\{bibliography\}",
                  r"\\chapter*{Bibliography}\\addcontentsline{toc}{chapter}{Bibliography}\\markboth{Bibliography}{Bibliography}",
                  body, count=1)
    return body


