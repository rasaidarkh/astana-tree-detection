CITE_GROUP_RE = re.compile(r"\[((?:@[A-Za-z0-9_]+(?:\s*;\s*)?)+)\]")
SINGLE_CITE_RE = re.compile(r"@([A-Za-z0-9_]+)")


def replace_citations(text: str) -> str:
    def sub(m: re.Match) -> str:
        nums = []
        for key in (sk.group(1) for sk in SINGLE_CITE_RE.finditer(m.group(1))):
            nums.append(str(CITATIONS.get(key, "?")))
        return "[" + ", ".join(nums) + "]"
    return CITE_GROUP_RE.sub(sub, text)


def md_to_latex(md_text: str) -> str:
    """Run pypandoc, return LaTeX body.

    `--wrap=none` is required: pandoc's default wrapping can split inline
    `\\textbf{...}` spans across paragraph breaks when the bold text contains
    multi-byte Unicode (e.g. Cyrillic / Kazakh), which makes the output
    LaTeX-invalid (a `\\text@command` argument cannot cross a paragraph end).

    After conversion we post-process the result to collapse blank lines
    inside `\\begin{longtable}...\\end{longtable}` column specs — pandoc still
    emits blank paragraphs between column lines in the table preamble, which
    breaks LaTeX (the longtable column-spec argument cannot contain `\\par`).
    """
    tex = pypandoc.convert_text(
        md_text, "latex", format="md",
        extra_args=["--top-level-division=chapter", "--wrap=none"],
    )

    # Collapse blank lines inside every longtable environment. Pandoc still
    # emits blank paragraphs between column-spec lines in the table preamble,
    # which breaks LaTeX. We do a line-by-line scan instead of a single regex
    # for robustness against nested braces.
    out_lines: list[str] = []
    inside = 0
    for line in tex.splitlines():
        stripped = line.strip()
        if stripped.startswith("\\begin{longtable}"):
            inside += 1
        # drop empty lines while inside a longtable
        if inside > 0 and stripped == "":
            continue
        out_lines.append(line)
        if stripped.startswith("\\end{longtable}"):
            inside = max(0, inside - 1)
    tex = "\n".join(out_lines) + "\n"

    # Strip the explicit `Chapter N.` / `N.M[.K]` numbering that we ship in the
    # Markdown headings. LaTeX/memoir auto-numbers sections within each chapter,
    # so leaving the explicit numbers in produces double-numbering like
    # "Chapter 3. Chapter 3." or "3.3.5 3.3.5". The reference text in the body
    # ("see Section 3.2.3") is intentionally left as plain text.
    tex = re.sub(
        r"\\chapter\{Chapter\s+\d+\.\s*(.+?)\}",
        r"\\chapter{\1}", tex,
    )
    tex = re.sub(
        r"\\(section|subsection|subsubsection|paragraph)\{(?:\d+(?:\.\d+)*\.?)\s+(.+?)\}",
        r"\\\1{\2}", tex,
    )

    # Pandoc emits longtables with equal-width p{...} columns regardless of
    # content. The result is that 2-character cells get the same width as
    # 50-character cells — model names wrap awkwardly while short numerics
    # have wasted space. Replace pandoc's auto-width spec with a content-
    # aware allocation: first column wider (row label), middle columns auto
    # (`l`), last column flexible (`p{}`) for notes/comments. Also strip the
    # `\begin{minipage}` wrappers pandoc adds around every header cell —
    # they add awkward vertical padding without contributing to the layout.
    tex = _fix_longtable_styles(tex)

    tex = _caption_longtables(tex)

    tex = _number_display_equations(tex)

    return tex


def _caption_longtables(latex: str) -> str:
    r"""Turn a bold caption paragraph that precedes a longtable
    (`\textbf{Table N --- ...}`) into a real \caption{} attached to the
    longtable, so the table appears in \listoftables with an auto number.

    Pandoc renders our markdown table captions as an ordinary bold paragraph
    above the table and gives the longtable no \caption, so \listoftables is
    empty and the manual "Table 2.1" numbers (which repeat) are never checked
    by LaTeX. We strip the manual "Table N --- " prefix, keep the descriptive
    text as the float caption, and let LaTeX number it (\caption -> LoT entry).
    longtable's own \caption produces a LoT line and an in-text "Table X:".
    """
    # Pandoc structure for a captionless markdown table is:
    #   \textbf{Table N --- <caption text>}
    #
    #   {\def\LTcaptype{none} % do not increment counter
    #   \begin{longtable}[]{@{}<spec>@{}}
    #   ...
    #   \end{longtable}
    #   }
    # The `\LTcaptype{none}` wrapper deliberately suppresses numbering/caption.
    # We remove that wrapper and inject a real \caption{} as the longtable's
    # first row, so LaTeX numbers the table and lists it in \listoftables.
    cap_re = re.compile(
        r"\\textbf\{Table[~ ]+[\d.]+[ ]*(?:---|--|—|-|:)[ ]*(.+?)\}\s*"
        r"\{\\def\\LTcaptype\{none\}[^\n]*\n"
        r"(\\begin\{longtable\}\[\]\{@\{\}.*?@\{\}\})"
        r"(.*?\\end\{longtable\})\s*"
        r"\}",
        re.DOTALL,
    )

    def repl(m: re.Match) -> str:
        caption = m.group(1).strip().rstrip(".")
        open_tbl = m.group(2)
        body_and_end = m.group(3)
        # \caption + \endfirsthead so the caption (and its LoT entry) appears
        # only on the FIRST page of a multi-page longtable; continuation pages
        # would otherwise repeat the caption and emit a duplicate LoT line.
        return (open_tbl + "\n\\caption{" + caption + "}\\\\\n\\endfirsthead\n"
                + body_and_end)

    return cap_re.sub(repl, latex)


def _number_display_equations(latex: str) -> str:
    r"""Convert pandoc's unnumbered display math \[ ... \] into numbered
    equation environments, so display formulas carry (chapter.n) numbers like
    the AITU reference diploma. Pandoc renders markdown $$...$$ as

        \[
        ... \]

    We replace each such block with \begin{equation} ... \end{equation}.
    Inline math \( ... \) and already-numbered environments are left untouched.
    """
    # Non-greedy match of a top-level \[ ... \] block. Pandoc never nests these.
    eq_re = re.compile(r"\\\[(.+?)\\\]", re.DOTALL)

    def repl(m: re.Match) -> str:
        body = m.group(1).strip()
        # Skip if it already contains an alignment/equation environment.
        if "\\begin{" in body:
            return m.group(0)
        return "\\begin{equation}\n" + body + "\n\\end{equation}"

    return eq_re.sub(repl, latex)


def _fix_longtable_styles(latex: str) -> str:
    """Rework pandoc's verbose longtable column specs into content-aware
    p{} widths. Pandoc's default behaviour is to give every column an equal
    1/N share of the typeblock, which makes long-text cells wrap awkwardly
    while short cells waste horizontal space. We scan the table body, find
    the longest cell per column, and allocate widths proportional to those
    maxima — clamped to a [6%, 45%] range and renormalised to 92% of
    \\linewidth so tabcolseps fit comfortably."""

    # First strip the minipage wrapper that pandoc adds around every header
    # cell. We do this BEFORE width allocation so the header content is part
    # of the per-column length statistics.
    latex = re.sub(
        r"\\begin\{minipage\}\[b\]\{\\linewidth\}\\raggedright\s*"
        r"(.+?)"
        r"\s*\\end\{minipage\}",
        lambda m: r"\textbf{" + m.group(1).strip() + r"}",
        latex,
        flags=re.DOTALL,
    )

    # Match a complete longtable environment so we can read its body to size
    # the columns. The non-greedy `(.+?)` between the opening brace and
    # `\end{longtable}` captures the column-header + body region.
    table_re = re.compile(
        r"(\\begin\{longtable\}\[\]\{@\{\}\s*"
        r"((?:>\{\\raggedright\\arraybackslash\}p\{\(\\linewidth - \d+\\tabcolsep\) \* \\real\{[\d.]+\}\}\s*)+)"
        r"@\{\}\})"
        r"(.+?)"
        r"(\\end\{longtable\})",
        re.DOTALL,
    )

    def _strip_for_length(cell: str) -> str:
        """Approximate the visual length of a LaTeX cell by stripping
        commands but keeping their arguments. \\textbf{X} -> X."""
        s = cell
        s = re.sub(r"\\(textbf|texttt|emph|textit|textsf|textsc)\{([^{}]*)\}", r"\2", s)
        s = re.sub(r"\\[a-zA-Z]+\*?\s*", "", s)  # drop remaining commands
        s = re.sub(r"\{|\}", "", s)
        return s.strip()

    def replace_table(m: re.Match) -> str:
        spec_block = m.group(2)
        body = m.group(3)
        n = len(re.findall(r"\\real\{([\d.]+)\}", spec_block))

        # Extract every row: rows end with `\\` followed by a newline. The
        # first row is the header; subsequent rows are the body.
        rows: list[list[str]] = []
        for raw_row in re.findall(r"(?<![\\&])((?:[^\\]|\\(?!\\))*?)\\\\(?:\s|$)", body):
            cells = raw_row.split("&")
            if len(cells) == n:
                rows.append([_strip_for_length(c) for c in cells])

        if not rows:
            even = round(0.92 / n, 3)
            specs = [rf"p{{{even}\linewidth}}" for _ in range(n)]
        else:
            # Strategy: treat the column header as a hard minimum-content
            # length (so the header never gets squeezed below its own text
            # width) and use body content as the "preferred" length. The
            # natural width of a column is then max(header, body) clamped to
            # a sensible range, and we allocate proportionally to natural
            # widths with a per-column floor so short columns still have room.
            header_row = rows[0]
            body_rows = rows[1:] if len(rows) > 1 else rows

            # Clamp header length to [4, 18] — headers above 18 chars are
            # rare and usually have spaces that can wrap onto a second line.
            header_chars = [max(4, min(18, len(c))) for c in header_row]
            # Clamp body content per cell to [4, 30] then take max per column.
            body_chars = [4] * n
            for row in body_rows:
                for i, cell in enumerate(row):
                    body_chars[i] = max(body_chars[i], min(30, len(cell)))
            # Natural width signal = max(header, body).
            natural = [max(h, b) for h, b in zip(header_chars, body_chars)]

            total = sum(natural)
            # Allocate within a typeblock budget that depends on N: wider
            # tables get a smaller budget so per-column floor still fits.
            budget = 0.95 if n <= 5 else 0.97
            raw_widths = [budget * c / total for c in natural]

            # Per-column floor — different for narrow vs wide tables.
            # For a 7-col table at floor=0.10 we'd need 0.70 just for floors,
            # which leaves no headroom for content variation — so the floor
            # is scaled down for wider tables.
            floor = {2: 0.25, 3: 0.15, 4: 0.12, 5: 0.10}.get(n, 0.09)
            widths = [max(floor, w) for w in raw_widths]

            # Renormalise so widths sum to `budget` without exceeding it.
            s = sum(widths)
            if s > budget:
                widths = [w * budget / s for w in widths]

            # Wrap each p{} in `>{\raggedright\arraybackslash}` so text is
            # left-aligned (ragged-right edge) instead of justified. Justified
            # cells try to stretch words to fill the line, and when a cell
            # contains a long unbreakable monospace identifier
            # (e.g. `confidence_threshold`, 20 chars), justification can
            # cause letters to overlap or run past the cell boundary.
            # Ragged-right gives LaTeX freedom to break wherever it can.
            specs = [
                rf">{{\raggedright\arraybackslash}}p{{{round(w, 3)}\linewidth}}"
                for w in widths
            ]

        new_open = r"\begin{longtable}[]{@{}" + " ".join(specs) + r"@{}}"

        # For wide tables (≥ 6 cols) wrap the whole longtable in `\small`
        # so the content fits without further width squeezing.
        if n >= 6:
            return r"{\small " + new_open + body + m.group(4) + "}"
        return new_open + body + m.group(4)

    return table_re.sub(replace_table, latex)


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"  wrote {path.relative_to(HERE)}  ({len(content):,} chars)")


def _strip_chapter_header(latex: str, expected_title: str | None = None) -> str:
    """Pandoc emits `\\chapter{Title}\\label{...}` at the top. We sometimes
    want only the body when we control the chapter wrapper ourselves."""
    return re.sub(r"^\\chapter\{[^}]*\}\\label\{[^}]*\}\s*", "", latex,
                  count=1, flags=re.MULTILINE)


